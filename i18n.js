  function translateText(raw, lang = currentLang) {
    if (lang !== 'es' || typeof raw !== 'string' || !raw) return raw;
    const m = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!m || !m[2]) return raw;
    const [, lead, core, trail] = m;
    const norm = core.replace(/\s+/g, ' ').trim();
    if (!norm) return raw;

    if (Object.prototype.hasOwnProperty.call(DICT_ES, norm)) {
      return lead + DICT_ES[norm] + trail;
    }
    for (let i = 0; i < PATTERNS_ES.length; i++) {
      const [rx, rep] = PATTERNS_ES[i];
      if (rx.test(norm)) {
        return lead + norm.replace(rx, rep) + trail;
      }
    }
    return raw;
  }

  function isProtectedNode(node) {
    let el = node.nodeType === 1 ? node : node.parentElement;
    while (el && el !== document.documentElement) {
      if (SKIP_TAGS.has(el.tagName)) return true;
      if (el.id && PROTECTED_IDS.has(el.id)) return true;
      if (el.hasAttribute && el.hasAttribute('data-no-i18n')) return true;
      el = el.parentElement;
    }
    return false;
  }

  function processTextNode(node, lang) {
    if (!node || node.nodeType !== 3) return;
    if (isProtectedNode(node)) return;
    const val = node.nodeValue;
    if (!val || !val.trim()) return;

    if (lang === 'es') {
      if (!origText.has(node) || (lastEsText.has(node) && val !== lastEsText.get(node))) {
        // Fresh text node or programmatically updated by JS with new English text
        origText.set(node, val);
      }
      const src = origText.get(node);
      const translated = translateText(src, 'es');
      if (translated !== src) {
        lastEsText.set(node, translated);
        if (node.nodeValue !== translated) node.nodeValue = translated;
      }
    } else if (origText.has(node)) {
      const src = origText.get(node);
      if (lastEsText.has(node) && node.nodeValue === lastEsText.get(node)) {
        node.nodeValue = src;
      }
      lastEsText.delete(node);
    }
  }

  function processElementAttrs(el, lang) {
    if (!el || el.nodeType !== 1 || SKIP_TAGS.has(el.tagName)) return;
    if (el.hasAttribute('data-no-i18n')) return;
    let mapOrig = origAttrs.get(el);
    let mapLast = lastEsAttrs.get(el);

    for (let i = 0; i < ATTRS.length; i++) {
      const attr = ATTRS[i];
      if (!el.hasAttribute(attr)) continue;
      const cur = el.getAttribute(attr);
      if (!cur || !cur.trim()) continue;

      if (lang === 'es') {
        if (!mapOrig) { mapOrig = {}; origAttrs.set(el, mapOrig); }
        if (!mapLast) { mapLast = {}; lastEsAttrs.set(el, mapLast); }
        if (!(attr in mapOrig) || (attr in mapLast && cur !== mapLast[attr])) {
          mapOrig[attr] = cur;
        }
        const translated = translateText(mapOrig[attr], 'es');
        if (translated !== mapOrig[attr]) {
          mapLast[attr] = translated;
          if (cur !== translated) el.setAttribute(attr, translated);
        }
      } else if (mapOrig && (attr in mapOrig)) {
        if (mapLast && cur === mapLast[attr]) {
          el.setAttribute(attr, mapOrig[attr]);
        }
        if (mapLast) delete mapLast[attr];
      }
    }
  }

  function walkAndApply(root, lang) {
    if (!root) return;
    applying = true;
    try {
      if (root.nodeType === 1) processElementAttrs(root, lang);
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      let node;
      while ((node = walker.nextNode())) {
        if (node.nodeType === 3) {
          processTextNode(node, lang);
        } else if (node.nodeType === 1) {
          processElementAttrs(node, lang);
        }
      }
    } finally {
      applying = false;
    }
  }

  let pendingMutations = [];
  function ensureObserver() {
    if (observer || !document.body) return;
    observer = new MutationObserver((mutations) => {
      if (applying || currentLang !== 'es') return;
      for (let i = 0; i < mutations.length; i++) pendingMutations.push(mutations[i]);
      if (scheduled) return;
      scheduled = true;
      queueMicrotask(() => {
        scheduled = false;
        const batch = pendingMutations;
        pendingMutations = [];
        if (applying || currentLang !== 'es' || !batch.length) return;
        applying = true;
        try {
          for (let i = 0; i < batch.length; i++) {
            const m = batch[i];
            if (m.type === 'characterData') {
              processTextNode(m.target, 'es');
            } else if (m.type === 'attributes') {
              processElementAttrs(m.target, 'es');
            } else if (m.type === 'childList') {
              for (const n of m.addedNodes) {
                if (n.nodeType === 3) processTextNode(n, 'es');
                else if (n.nodeType === 1) walkAndApply(n, 'es');
              }
            }
          }
        } finally {
          applying = false;
        }
      });
    });
  }

  function syncSwitcherUI(lang) {
    const seg = document.getElementById('seg-lang');
    if (seg) {
      seg.querySelectorAll('button[data-lang]').forEach((b) => {
        b.classList.toggle('active-lang', b.dataset.lang === lang);
        b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false');
      });
    }
  }

  function setLang(lang, opts = {}) {
    const next = lang === 'es' ? 'es' : 'en';
    currentLang = next;
    if (opts.persist !== false) {
      try { localStorage.setItem(STORAGE_KEY, next); } catch { }
    }
    document.documentElement.lang = next;
    document.title = next === 'es' ? translateText(origDocTitle, 'es') : origDocTitle;
    syncSwitcherUI(next);

    if (observer) observer.disconnect();
    if (document.body) {
      walkAndApply(document.body, next);
      if (next === 'es') {
        ensureObserver();
        observer.observe(document.body, {
          childList: true,
          subtree: true,
          characterData: true,
          attributes: true,
          attributeFilter: ATTRS
        });
      }
    }
    return next;
  }

  function init() {
    origDocTitle = document.title || origDocTitle;
    let saved = 'en';
    try {
      const s = localStorage.getItem(STORAGE_KEY);
      if (s === 'es' || s === 'en') saved = s;
    } catch { }
    syncSwitcherUI(saved);
    if (saved === 'es') {
      setLang('es', { persist: false });
    } else {
      document.documentElement.lang = 'en';
    }
    return saved;
  }

